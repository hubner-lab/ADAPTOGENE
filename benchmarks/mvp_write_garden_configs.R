#!/usr/bin/env Rscript
# =============================================================================
# mvp_write_garden_configs.R -- configs for the Lind & Lotterhos garden replication (journal 09).
#
# TWO configs per seed, because the pipeline's method registry has exactly one `rda_offset`
# entry (workflow/methods/maladaptation.py) and common.smk hard-errors on any method key it
# does not know. RDA-corrected and RDA-uncorrected are two distinct implementations in
# Lind & Lotterhos 2025, so they are run as two PASSES over the same gardens rather than as
# two method blocks -- no pipeline code is touched:
#
#   config_MVP{seed}_g.yaml      pass A: gradient_forest + geometric_offset + rda_offset
#                                        with condition_pcs: 0   (= RDA-uncorrected)
#   config_MVP{seed}_grdac.yaml  pass B: rda_offset ONLY, condition_pcs: k_best
#                                        (= RDA-corrected). Cheap: no GF, no LFMM2 refit.
#
# Both point Climate.custom.future_table at ONE per-seed file, MVP{seed}_env_garden.tsv, which
# the driver (benchmarks/mvp_garden_run.sh) rewrites before each garden. The config never
# changes during a sweep; only that table does.
#
# Settings and why:
#   axes: 2         -- fixed instead of `auto`. Measured on all 126 journal-08 RDA runs:
#                      rda_axes_used = 2 on 100% of them (2 predictors -> K_max = 2), so this
#                      changes no result and removes 999 permutations from every garden.
#   snp_sets        -- the four panels the replication needs, listed explicitly rather than
#                      `all`, so the sweep does not also re-run union/solo/rand_best2/3, which
#                      exist on disk from journal 08 but are not part of their comparison:
#                        all         -> their "all" marker set
#                        best        -> their "adaptive" marker set
#                        rand_best1  -> their "neutral" marker set
#                        truth       -> our own ceiling, not part of their design
#   spatial_correction: without  -- as journal 08; the other two methods are nospatial-only and
#                      mode=climate has never been run for these projects.
#   random_model: false          -- GF's neutral model feeds only importance plots.
#
# Usage:  Rscript mvp_write_garden_configs.R [--seeds=all|CSV] [--ntree=500]
# =============================================================================

suppressPackageStartupMessages(library(data.table))

PIPELINE_ROOT <- Sys.getenv("PIPELINE_ROOT", "/pipeline")
source(file.path(PIPELINE_ROOT, "benchmarks/lib_detection.R"))

args    <- parse_kv_args(commandArgs(trailingOnly = TRUE))
opt     <- function(k, d) if (is.null(args[[k]]) || !nzchar(args[[k]])) d else args[[k]]
SEEDS_A <- opt("seeds", "all")
NTREE   <- opt("ntree", "500")
CPU_PER_JOB <- as.integer(opt("cpu_per_job", "3"))   # threads reserved per rda_offset job

# Panel roster, in the vocabulary of Lind & Lotterhos 2025 plus our own additions:
#   all          their "all"      -- every tested SNP
#   neutral_all  their "neutral"  -- LG 11-20, the QTN-free linkage groups (their definition)
#   truth        their "adaptive" -- the true QTN loci (an ORACLE panel, not obtainable in practice)
#   union        ours, max recall     -- any of LFMM/RDA/EMMAX
#   best         ours, >= 2 of 3      -- the journal-07 anchor scheme S1
#   intersect3   ours, max precision  -- all three methods agree
#   rand_best1   ours, size-matched random floor (keeps set SIZE separable from set QUALITY)
SETS <- c("all", "neutral_all", "truth", "union", "best", "intersect3", "rand_best1")

MAN   <- fread(file.path(PIPELINE_ROOT, "benchmarks/mvp_seeds.tsv"),
               colClasses = c("seed" = "character"))
SEEDS <- if (SEEDS_A == "all") MAN$seed else strsplit(SEEDS_A, ",", fixed = TRUE)[[1]]

sets_yaml <- function() c(
    # Tables only: the garden sweep consumes genetic_offset_site.tsv and discards every plot.
    # Measured on this sweep: plots were ~32 of ~48 jobs per garden, and plot_gf_cumimp on the
    # ~10k-SNP `all` forest was the largest memory consumer (OOM-killed two lanes at 24 GB).
    "  emit_plots: false",
    "  snp_sets:", paste0("    - ", SETS))

mala_A <- function() c(
    "",
    "#-----------------------------------------------------------------------------",
    "# MALADAPTATION -- journal 09 garden sweep, PASS A.",
    "# Generated by benchmarks/mvp_write_garden_configs.R; do not hand-edit, regenerate.",
    "# GFoffset + LFMM2offset(geometric) + RDA-uncorrected, in the vocabulary of",
    "# Lind & Lotterhos 2025. RDA-corrected is pass B (config_MVP{seed}_grdac.yaml).",
    "#-----------------------------------------------------------------------------",
    "Maladaptation:",
    "  methods:",
    "    gradient_forest:",
    sprintf("      ntree: '%s'", NTREE),
    "      cor_threshold: '0.5'",
    "      spatial_correction: without",
    "      random_model: false",
    "    geometric_offset:",
    "      scale: true",
    "      k: ''",
    "    rda_offset:",
    "      axes: 2                                # K_max on 2 predictors; measured, not guessed",
    "      axis_alpha: 0.05",
    "      permutations: 99                       # unused at axes: 2, kept low",
    "      condition_pcs: 0                       # RDA-uncorrected",
    "      seed: 42",
    sets_yaml()
)

mala_B <- function(kbest) c(
    "",
    "#-----------------------------------------------------------------------------",
    "# MALADAPTATION -- journal 09 garden sweep, PASS B: RDA-corrected only.",
    "# Generated by benchmarks/mvp_write_garden_configs.R; do not hand-edit, regenerate.",
    "# Same gardens, same SNP sets; the only difference from pass A is condition_pcs, which",
    "# is what separates the two RDA implementations in Lind & Lotterhos 2025.",
    "#-----------------------------------------------------------------------------",
    "Maladaptation:",
    "  methods:",
    "    rda_offset:",
    "      axes: 2",
    "      axis_alpha: 0.05",
    "      permutations: 99",
    sprintf("      condition_pcs: %d                       # RDA-corrected (k_best of this seed)", kbest),
    "      seed: 42",
    sets_yaml()
)

patch <- function(L, s, block) {
    if (any(grepl("^Maladaptation:", L))) stop("base config already has a Maladaptation block")
    i <- grep("^\\s*present_table:", L)
    if (length(i) != 1L) stop("expected exactly one present_table: line, got ", length(i))
    indent <- sub("^(\\s*).*$", "\\1", L[i])
    L <- append(L, sprintf("%sfuture_table: \"MVP%s_env_garden.tsv\"   # rewritten per garden",
                           indent, s), after = i)

    # `cpu` MUST be set for this sweep. Without it common.smk takes os.cpu_count() - 2, which
    # inside the container is 190 (it sees all host cores), and `rda_offset` declares
    # `threads: CPU` -- so Snakemake gives one RDA job the entire lane and runs the gardens'
    # offsets one at a time, while the R process itself is essentially single-threaded.
    # Measured effect of the default: 25 of 120 cores in use across 14 lanes.
    if (!any(grepl("^cpu:", L))) {
        j <- grep("^project_name:", L)
        L <- append(L, sprintf("cpu: %d   # journal 09: caps rda_offset's `threads: CPU` request", CPU_PER_JOB),
                    after = if (length(j)) j[1] else 0L)
    }
    c(L, block)
}

    # Clone lanes: same seed, different project_name, so several gardens of one seed can run at
    # once (benchmarks/mvp_clone_project.sh). Only project_name and the per-lane garden table
    # change -- Input.*, Filter.*, LD.*, sNMF.* and the Maladaptation block are byte-identical,
    # and every _work/_intermediate filename derives from the VCF basename, not project_name.
CLONE_TAGS <- {
    x <- opt("clone_tags", "")
    if (nzchar(x)) strsplit(x, ",", fixed = TRUE)[[1]] else character(0)
}

retag <- function(L, s, tag) {
    L <- sub(sprintf("^project_name:\\s*MVP%s\\s*$", s),
             sprintf("project_name: MVP%s%s", s, tag), L)
    sub(sprintf("MVP%s_env_garden\\.tsv", s), sprintf("MVP%s%s_env_garden.tsv", s, tag), L)
}

for (s in SEEDS) {
    base_f <- file.path(PIPELINE_ROOT, sprintf("config_MVP%s.yaml", s))
    if (!file.exists(base_f)) stop("Missing base config: ", base_f)
    L <- readLines(base_f, warn = FALSE)
    kbest <- MAN[seed == s, k_best]
    if (length(kbest) != 1L || is.na(kbest)) stop("no k_best for seed ", s)

    A <- patch(L, s, mala_A()); B <- patch(L, s, mala_B(kbest))
    writeLines(A, file.path(PIPELINE_ROOT, sprintf("config_MVP%s_g.yaml", s)))
    writeLines(B, file.path(PIPELINE_ROOT, sprintf("config_MVP%s_grdac.yaml", s)))

    for (tag in CLONE_TAGS) {
        At <- retag(A, s, tag); Bt <- retag(B, s, tag)
        if (!any(grepl(sprintf("^project_name: MVP%s%s$", s, tag), At)))
            stop("project_name not retagged for seed ", s, " tag ", tag)
        writeLines(At, file.path(PIPELINE_ROOT, sprintf("config_MVP%s%s_g.yaml", s, tag)))
        writeLines(Bt, file.path(PIPELINE_ROOT, sprintf("config_MVP%s%s_grdac.yaml", s, tag)))
    }
    message(sprintf("wrote configs for MVP%s (k_best=%d) + %d clone lane(s)",
                    s, kbest, length(CLONE_TAGS)))
}
message("\nDone: ", length(SEEDS), " seed(s) x ", 2 * (1 + length(CLONE_TAGS)), " configs.")
